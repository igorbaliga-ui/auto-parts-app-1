const NAME_MAX_LENGTH = 30;

// Буквы (рус/лат), пробел, дефис и апостроф — типичный набор для имени.
// Цифры, HTML-теги и прочие спецсимволы отбрасываются.
const ALLOWED_NAME_CHARS = /[^a-zA-Zа-яА-ЯёЁ\s'-]/g;

/**
 * Приводит ввод имени к безопасному виду: обрезает до 30 символов и убирает
 * цифры/спецсимволы (включая потенциальную HTML-разметку). На некоторых
 * Android-клавиатурах (автоподстановка, голосовой ввод, IME) атрибут
 * maxLength у поля не всегда соблюдается, поэтому ограничение дополнительно
 * применяется в JS при каждом вводе.
 */
export function sanitizeNameInput(raw: string): string {
  return raw.replace(ALLOWED_NAME_CHARS, '').slice(0, NAME_MAX_LENGTH);
}

const VIN_MAX_LENGTH = 17;

/**
 * Приводит ввод VIN-кода к безопасному виду: обрезает до 17 символов и
 * оставляет только латинские буквы и цифры (сам VIN не содержит других
 * символов). HTML-атрибут maxLength на некоторых Android-клавиатурах
 * (автоподстановка, голосовой ввод, IME) не всегда соблюдается, поэтому
 * ограничение дополнительно применяется в JS при каждом вводе — так поле
 * гарантированно не примет строку длиннее нужной и без посторонних символов,
 * которые могли бы попасть дальше в запрос к серверу.
 */
export function sanitizeVinInput(raw: string): string {
  return raw
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, '')
    .slice(0, VIN_MAX_LENGTH);
}

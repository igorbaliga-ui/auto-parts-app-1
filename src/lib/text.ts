const PARTS_MAX_LENGTH = 1000;
const CITY_MAX_LENGTH = 20;

// Убирает управляющие символы и символы, из которых можно собрать HTML/скрипт
// (<, >, фигурные скобки, обратные кавычки), не трогая обычную пунктуацию,
// которой клиенты описывают запчасти (запятые, точки, дефисы, слэши, номера).
// eslint-disable-next-line no-control-regex
const DANGEROUS_CHARS = /[<>{}`\x00-\x08\x0B\x0C\x0E-\x1F]/g;

/**
 * Приводит ввод поля «Интересующие запчасти» к безопасному виду: обрезает
 * до 1000 символов и вырезает символы, потенциально пригодные для HTML/скрипт-
 * инъекции. Обычная пунктуация и переносы строк сохраняются — это свободный текст.
 */
export function sanitizePartsInput(raw: string): string {
  return raw.replace(DANGEROUS_CHARS, '').slice(0, PARTS_MAX_LENGTH);
}

// Город — только буквы (рус/лат), пробел и дефис (нужен для «Ростов-на-Дону»,
// «Санкт-Петербург»). Цифры, HTML-теги и прочие спецсимволы отбрасываются.
const ALLOWED_CITY_CHARS = /[^a-zA-Zа-яА-ЯёЁ\s-]/g;

/**
 * Приводит ввод поля «Город» к безопасному виду: обрезает до 20 символов и
 * убирает всё, кроме букв, пробела и дефиса. На некоторых Android-клавиатурах
 * (автоподстановка, голосовой ввод, IME) атрибут maxLength у поля не всегда
 * соблюдается, поэтому ограничение дополнительно применяется в JS.
 */
export function sanitizeCityInput(raw: string): string {
  return raw.replace(ALLOWED_CITY_CHARS, '').slice(0, CITY_MAX_LENGTH);
}

const CAR_NAME_MAX_LENGTH = 25;

/**
 * Приводит ввод поля «Название автомобиля» (личный кабинет «Гараж») к
 * безопасному виду: обрезает до 25 символов (совпадает с ограничением на
 * сервере) и вырезает символы, из которых можно собрать HTML/скрипт-
 * инъекцию. Буквы, цифры и обычная пунктуация («Toyota Camry», «Ford Focus III»)
 * сохраняются — это свободный текст.
 */
export function sanitizeCarNameInput(raw: string): string {
  return raw.replace(DANGEROUS_CHARS, '').slice(0, CAR_NAME_MAX_LENGTH);
}

export const MILEAGE_MAX_LENGTH = 7; // до 9 999 999 км — с запасом, ограничение по значению ниже
export const MILEAGE_MAX_VALUE = 2_000_000;

/**
 * Приводит ввод поля «Пробег» (личный кабинет «Гараж») к безопасному виду:
 * оставляет только цифры и обрезает до разумной длины — совпадает с
 * ограничением на сервере. Числовое поле, поэтому никакой другой пунктуации
 * не допускается в принципе (это не текст, а строго число в км).
 */
export function sanitizeMileageInput(raw: string): string {
  return raw.replace(/\D/g, '').slice(0, MILEAGE_MAX_LENGTH);
}